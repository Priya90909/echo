import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
async function register(page, name) {
  await page.goto("/register");
  await page.getByLabel("Your name").fill(name);
  await page
    .getByLabel("Email", { exact: true })
    .fill(`${name.toLowerCase().replaceAll(" ", "-")}-${Date.now()}@echo.test`);
  await page
    .getByLabel("Password", { exact: true })
    .fill("e2e-long-secure-password");
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page).toHaveURL(/home/);
}
test("two listeners synchronize playback, chat and rejoin", async ({
  browser,
}) => {
  test.skip(true, "EchoRooms is disabled in the current release");
  const contextA = await browser.newContext(),
    contextB = await browser.newContext();
  const a = await contextA.newPage(),
    b = await contextB.newPage();
  try {
    await register(a, "Room Host");
    await register(b, "Room Guest");
    await a.goto("/rooms");
    await a.getByRole("button", { name: "Create a room" }).click();
    await expect(a).toHaveURL(/code=[a-f\d]{8}/);
    await expect(
      a.getByRole("heading", { name: "Host controls" }),
    ).toBeVisible();
    await b.goto(a.url());
    await expect(b.getByText("Room Host · host")).toBeVisible();
    await expect(a.getByText("Room Guest", { exact: true })).toBeVisible();
    await a.getByLabel("Room track").selectOption({ label: "Emerald morning" });
    await expect(
      b.getByRole("button", { name: "Pause", exact: true }),
    ).toBeVisible();
    await a.getByRole("button", { name: "Pause room" }).click();
    await expect(
      b.getByRole("button", { name: "Play", exact: true }),
    ).toBeVisible();
    await b.getByLabel("Chat message").fill("Hello from another browser");
    await b.getByRole("button", { name: "Send", exact: true }).click();
    await expect(a.getByText("Hello from another browser")).toBeVisible();
    await b.reload();
    await expect(b.getByText("Room Host · host")).toBeVisible();
  } finally {
    await contextA.close();
    await contextB.close();
  }
});
test("artist upload is processed by FFmpeg and awaits approval", async ({
  page,
}) => {
  test.skip(
    !process.env.ECHO_E2E_LIVE,
    "Requires API, Redis, storage and worker",
  );
  test.setTimeout(60000);
  await register(page, "Upload Artist");
  await page.goto("/studio");
  await page.getByLabel("Artist name").fill("Original Test Artist");
  await page.getByLabel("Bio").fill("Original audio integration test");
  await page.getByRole("button", { name: "Open my studio" }).click();
  await page.getByRole("link", { name: "Upload music", exact: true }).click();
  const name = "Upload fixture " + Date.now();
  await page.getByLabel("Track title").fill(name);
  await page.getByLabel("Genre", { exact: true }).fill("Ambient");
  await page
    .getByLabel("Attribution and rights evidence")
    .fill("Synthetic audio generated by ECHO for integration testing.");
  await page.getByText("I own or have permission").locator("input").check();
  const bytes = await readFile("work/local-s3/echo/demo/Emerald-morning.wav");
  await page.getByLabel("Audio ·").setInputFiles({
    name: "original-demo.wav",
    mimeType: "audio/wav",
    buffer: bytes,
  });
  await page.getByRole("button", { name: "Submit for processing" }).click();
  await expect(page.getByRole("status")).toContainText("Upload accepted");
  await page.getByRole("link", { name: "Overview", exact: true }).click();
  await expect
    .poll(
      async () => {
        const response = await page.request.get("/api/studio");
        const body = await response.json();
        return body.tracks.find((t) => t.title === name)?.status;
      },
      { timeout: 30000 },
    )
    .toBe("review");
  await page.reload();
  await expect(page.getByText("review", { exact: true })).toBeVisible();
});
