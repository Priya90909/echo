import mongoose from "mongoose";
import { CreateBucketCommand, HeadBucketCommand } from "@aws-sdk/client-s3";
import { config } from "./config.js";
import { User, Artist, Track } from "./models.js";
import { s3, store } from "./storage.js";
import bcrypt from "bcryptjs";
await mongoose.connect(config.MONGODB_URI);
try {
  await s3.send(new HeadBucketCommand({ Bucket: config.S3_BUCKET }));
} catch {
  await s3.send(new CreateBucketCommand({ Bucket: config.S3_BUCKET }));
}
const email = process.env.SEED_ADMIN_EMAIL,
  password = process.env.SEED_ADMIN_PASSWORD;
if (email && password) {
  if (password.length < 12)
    throw new Error("Seed password must be at least 12 characters");
  await User.updateOne(
    { email },
    {
      $setOnInsert: {
        name: "ECHO curator",
        email,
        passwordHash: await bcrypt.hash(password, 12),
        role: "admin",
      },
    },
    { upsert: true },
  );
}
let owner = await User.findOne({ email: "demo-catalog@echo.invalid" });
if (!owner)
  owner = await User.create({
    name: "ECHO demo synthesizer",
    email: "demo-catalog@echo.invalid",
    passwordHash: await bcrypt.hash(crypto.randomUUID(), 12),
    role: "artist",
  });
const artist = await Artist.findOneAndUpdate(
  { owner: owner._id },
  {
    $set: {
      name: "ECHO Demo Lab",
      bio: "Synthetic demonstration tones generated locally. These are not commercial recordings.",
    },
  },
  { upsert: true, new: true },
);
const entries = [
  ["Emerald morning", "Ambient", ["Calm", "Focused"], 220],
  ["Violet drift", "Electronic", ["Relaxed", "Nostalgic"], 164.81],
  ["Afterglow pulse", "Electronic", ["Energetic", "Happy"], 329.63],
  ["Quiet orbit", "Ambient", ["Focused", "Relaxed"], 261.63],
];
for (const [title, genre, moods, hz] of entries) {
  const rate = 22050,
    seconds = 30,
    n = rate * seconds;
  const buffer = Buffer.alloc(44 + n * 2);
  buffer.write("RIFF");
  buffer.writeUInt32LE(36 + n * 2, 4);
  buffer.write("WAVE", 8);
  buffer.write("fmt ", 12);
  buffer.writeUInt32LE(16, 16);
  buffer.writeUInt16LE(1, 20);
  buffer.writeUInt16LE(1, 22);
  buffer.writeUInt32LE(rate, 24);
  buffer.writeUInt32LE(rate * 2, 28);
  buffer.writeUInt16LE(2, 32);
  buffer.writeUInt16LE(16, 34);
  buffer.write("data", 36);
  buffer.writeUInt32LE(n * 2, 40);
  for (let i = 0; i < n; i++) {
    const t = i / rate,
      envelope = Math.min(t / 2, 1, (seconds - t) / 2);
    const wave =
      (Math.sin(2 * Math.PI * hz * t) +
        0.3 * Math.sin(2 * Math.PI * hz * 1.5 * t) +
        0.15 * Math.sin(2 * Math.PI * hz * 2 * t)) *
      0.15 *
      envelope;
    buffer.writeInt16LE(Math.round(wave * 32767), 44 + i * 2);
  }
  const key = `demo/${title.replaceAll(" ", "-")}.wav`;
  await store(key, buffer, "audio/wav");
  await Track.updateOne(
    { title, artist: artist._id },
    {
      $set: {
        genre,
        moods: [...moods],
        duration: seconds,
        isDemo: true,
        catalogRank: 1000,
        mediaKey: key,
        license: "original",
        attribution: "Generated by the ECHO seed script; synthetic demo audio.",
        rightsConfirmed: true,
        status: "published",
      },
    },
    { upsert: true },
  );
}
console.log("Seeded four clearly labeled synthetic demo tracks.");
await mongoose.disconnect();
